import math

def get_triangle(n):
    sum = 0
    for i in range(1,n+1):
        sum += i
    return sum

def get_factors(n):
    facs = 0
    for i in range(1,n+1):
        if n % i == 0:
            facs+=1
    return facs

def get_prime_factors(n):
    factors = []
    d=2
    while d*d <= n:
        while n % d == 0:
            factors.append(d)
            n=n//d
        d+=1
    if n > 1:
        factors.append(n)
    return factors

def get_factor_count(prime_facs):
    expos = dict()
    for num in prime_facs:
        if num in expos:
            expos[num] += 1
        else:
            expos[num] = 1
    f_list = []
    for k,v in expos.items():
        f_list.append(v+1)
    return math.prod(f_list)


